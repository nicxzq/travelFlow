function nav(keyword: string) {
  return `https://uri.amap.com/search?keyword=${encodeURIComponent(keyword)}`;
}

function event(
  dayId: string,
  index: number,
  startTime: string,
  endTime: string | undefined,
  title: string,
  category: TripEvent['category'],
  description: string,
  locationName: string,
): TripEvent {
  return {
    id: `${dayId}-event-${index}`,
    dayId,
    tripId,
    startTime,
    endTime,
    title,
    category,
    description,
    locationName,
    navigationUrl: nav(locationName),
    status: 'planned',
  };
}

