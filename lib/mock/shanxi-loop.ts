function nav(keyword: string) {
  return `https://uri.amap.com/search?keyword=${encodeURIComponent(keyword)}`;
}

function event(
  dayId: string,
  index: number,
  startTime: string,
  endTime: string | undefined,
  title: string,
  category: TripEvent['category'],
  description: string,
  locationName: string,
  transportMode?: TransportMode,
): TripEvent {
  const dayIndex = dayId.replace('day-', '');

  return {
    id: `r3-d${dayIndex}-e${index}`,
    dayId,
    tripId,
    startTime,
    endTime,
    title,
    category,
    description,
    locationName,
    geo: places[locationName],
    navigationUrl: nav(locationName),
    status: 'done',
    actualStatus: 'completed',
    transportMode,
  };
}

